/** Kurzbeschreibung zu einer Knopf-ID; für Skizzenwerkzeuge (t_…) die Hilfe des Werkzeugs (bis zum ersten Doppelpunkt-Satz). */
export function befehlHilfe(id, sketchTools = {}) {
  if (!id) return "";
  if (BEFEHLSHILFE[id]) return BEFEHLSHILFE[id];
  if (id.startsWith("t_") && sketchTools[id.slice(2)]) {
    const t = sketchTools[id.slice(2)];
    const i = t.indexOf(": ");
    return i > 0 && i < 30 ? t.slice(i + 2) : t;
  }
  if (id.startsWith("dm_")) return "Darstellungsart des 3D-Fensters.";
  if (id.startsWith("clip_")) return `Modell mit einer Ebene senkrecht zu ${id.slice(5)} aufschneiden, um ins Innere zu sehen.`;
  return "";
}
